#!/usr/bin/env node
// Generate the mechanical 1.0 evidence inventory. This records the current
// surface and evidence; it deliberately does not choose maintainer stability
// classifications for any SDK symbol.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = new Set(process.argv.slice(2));
const JSON_OUTPUT = "docs/one-point-zero-surface-inventory.json";
const MD_OUTPUT = "docs/one-point-zero-surface-inventory.md";
const BANNER = "<!-- Generated by scripts/generate-one-point-zero-inventory.mjs. Do not edit by hand; run `node scripts/generate-one-point-zero-inventory.mjs --write`. -->";

const SOURCE_FILES = [
    "docs/sdk-public-api.json",
    "docs/breaking-change-review-contract.json",
    "docs/release-decision-registry-receipt.json",
    "docs/one-point-zero-classification.json",
    "docs/migration-guide.md",
    "wrapper/package.json",
    "cli/package.json",
    "mcp/package.json",
    ".github/workflows/release.yml",
    ".github/workflows/ci-cli-release.yml",
    ".github/workflows/ci-mcp-release.yml",
    "scripts/check-release-dispatch-guard.mjs",
    "scripts/check-release-support-contract.mjs",
    "scripts/check-version-consistency.mjs",
];

function absolute(relativePath) {
    return path.join(root, relativePath);
}

function read(relativePath) {
    return fs.readFileSync(absolute(relativePath), "utf8");
}

function readJson(relativePath) {
    return JSON.parse(read(relativePath));
}

function unique(values) {
    return [...new Set(values)];
}

function lineNumberedMatches(relativePath, pattern) {
    const lines = read(relativePath).split("\n");
    const records = [];
    for (const [index, line] of lines.entries()) {
        if (pattern.test(line)) records.push({ line: index + 1, text: line.trim() });
        pattern.lastIndex = 0;
    }
    return records;
}

function extractStabilityAnnotations() {
    const records = [];
    const files = fs
        .readdirSync(absolute("wrapper"), { withFileTypes: true })
        .filter((entry) => entry.isFile() && entry.name.endsWith(".ts"))
        .map((entry) => `wrapper/${entry.name}`)
        .sort();

    for (const relativePath of files) {
        const lines = read(relativePath).split("\n");
        for (let index = 0; index < lines.length; index += 1) {
            const annotations = [...lines[index].matchAll(/@(stable|experimental|beta|deprecated)\b([^\n*]*)/g)];
            for (const annotation of annotations) {
                let symbol = null;
                for (let next = index + 1; next < Math.min(lines.length, index + 10); next += 1) {
                    const declaration = lines[next].match(
                        /(?:export\s+)?(?:declare\s+)?(?:async\s+)?(?:function|class|interface|type|const|let|var)\s+([A-Za-z_$][\w$]*)/,
                    );
                    const getter = lines[next].match(/get\s+([A-Za-z_$][\w$]*)\s*\(/);
                    if (declaration || getter) {
                        symbol = declaration?.[1] ?? getter?.[1] ?? null;
                        break;
                    }
                }
                records.push({
                    tag: annotation[1],
                    annotation: annotation[0].trim(),
                    symbol,
                    file: relativePath,
                    line: index + 1,
                });
            }
        }
    }
    return records;
}

function extractHeadings(relativePath) {
    return read(relativePath)
        .split("\n")
        .flatMap((line, index) => {
            const match = line.match(/^(#{2,3})\s+(.+?)\s*$/);
            return match ? [{ level: match[1].length, title: match[2], line: index + 1 }] : [];
        });
}

function workflowEvidence(relativePath) {
    const lines = read(relativePath).split("\n");
    const relevant = /workflow_dispatch|node-version|PACKAGE_(?:NAME|VERSION)|SDK_(?:VERSION|PEER_RANGE)|npm view .*clockify-sdk|Verify package|Verify tag|proof_only|dist\.integrity|dist\.attestations|published_now|registryPublished/;
    const markers = [];
    for (const [index, line] of lines.entries()) {
        if (relevant.test(line)) markers.push({ line: index + 1, text: line.trim() });
    }
    return {
        workflow: relativePath,
        workflowDispatch: lines.some((line) => /workflow_dispatch/.test(line)),
        tagTrigger: lines.some((line) => /tags:/.test(line)),
        parserRelevantLines: markers,
    };
}

function buildInventory() {
    const sdkContract = readJson("docs/sdk-public-api.json");
    const breakingContract = readJson("docs/breaking-change-review-contract.json");
    const classification = readJson("docs/one-point-zero-classification.json");
    // The maintainer classification is the source of truth for every decision.
    // A symbol or subpath with no entry stays "undecided" rather than silently
    // defaulting to stable.
    const decisionFor = (list, key, value) =>
        (classification?.[list] ?? []).find((entry) => entry[key] === value)?.decision ?? "undecided";
    const registry = readJson("docs/release-decision-registry-receipt.json");
    const manifests = [
        { id: "sdk", path: "wrapper/package.json", package: readJson("wrapper/package.json") },
        { id: "cli", path: "cli/package.json", package: readJson("cli/package.json") },
        { id: "mcp", path: "mcp/package.json", package: readJson("mcp/package.json") },
    ];

    const appearances = new Map();
    for (const symbol of sdkContract.rootSymbols) {
        const entry = appearances.get(symbol) ?? { name: symbol, root: false, subpaths: [] };
        entry.root = true;
        appearances.set(symbol, entry);
    }
    const subpaths = Object.entries(sdkContract.subpaths).map(([subpath, symbols]) => ({
        path: subpath,
        decision: decisionFor("subpaths", "path", subpath),
        symbols: [...symbols],
    }));
    for (const subpath of subpaths) {
        for (const symbol of subpath.symbols) {
            const entry = appearances.get(symbol) ?? { name: symbol, root: false, subpaths: [] };
            entry.subpaths.push(subpath.path);
            appearances.set(symbol, entry);
        }
    }

    const stabilityAnnotations = extractStabilityAnnotations();
    const rootSymbols = sdkContract.rootSymbols.map((name) => ({
        name,
        decision: decisionFor("symbols", "name", name),
        subpaths: appearances.get(name)?.subpaths ?? [],
    }));
    const symbolDecisions = [...appearances.values()].map((entry) => ({
        name: entry.name,
        decision: decisionFor("symbols", "name", entry.name),
        root: entry.root,
        subpaths: unique(entry.subpaths),
    }));

    return {
        schemaVersion: 1,
        status: "maintainer_classified",
        purpose: "Inventory the public 1.0 decision surface and carry the maintainer stability classification from docs/one-point-zero-classification.json.",
        generatedFrom: SOURCE_FILES,
        sdk: {
            packageName: sdkContract.packageName,
            rootSymbolCount: rootSymbols.length,
            uniqueSymbolCount: symbolDecisions.length,
            subpathCount: subpaths.length,
            rootSymbols,
            symbolDecisions,
            subpaths,
            stability: {
                annotations: stabilityAnnotations,
                deprecatedDeclarations: stabilityAnnotations.filter((entry) => entry.tag === "deprecated"),
                untaggedRootSymbols: rootSymbols
                    .filter((entry) => !stabilityAnnotations.some((annotation) => annotation.symbol === entry.name))
                    .map((entry) => entry.name),
            },
        },
        consumers: manifests.map(({ id, path: manifestPath, package: pkg }) => ({
            id,
            manifest: manifestPath,
            name: pkg.name,
            version: pkg.version,
            nodeEngine: pkg.engines?.node ?? null,
            sdkPeerRange: pkg.peerDependencies?.[sdkContract.packageName] ?? null,
        })),
        releaseWorkflowPeerParsing: [
            workflowEvidence(".github/workflows/release.yml"),
            workflowEvidence(".github/workflows/ci-cli-release.yml"),
            workflowEvidence(".github/workflows/ci-mcp-release.yml"),
            {
                source: "scripts/check-release-dispatch-guard.mjs",
                peerRelatedLines: lineNumberedMatches("scripts/check-release-dispatch-guard.mjs", /SDK_(?:VERSION|PEER)|clockify-sdk|peer/i),
            },
            {
                source: "scripts/check-version-consistency.mjs",
                peerRelatedLines: lineNumberedMatches("scripts/check-version-consistency.mjs", /peerDependencies|peer dependency|SDK_PACKAGE/i),
            },
        ],
        knownPre1xBreakingChanges: breakingContract.breakingChanges,
        migrationGuide: {
            path: "docs/migration-guide.md",
            headings: extractHeadings("docs/migration-guide.md"),
            hasOnePointZeroClosure: extractHeadings("docs/migration-guide.md").some((heading) => heading.title === "1.0 SDK closure"),
        },
        registry: {
            source: "docs/release-decision-registry-receipt.json",
            status: registry.status,
            queriedAt: registry.queriedAt,
            capturedAgainstSha: registry.capturedAgainstSha,
            packages: registry.packages,
        },
        decisionPosture: {
            decision: "released_1_0",
            symbolClassification: "classified",
            reason: "Every public symbol and subpath carries a maintainer decision (docs/one-point-zero-classification.json, 2026-08-05), and the coordinated 1.0 release has been taken: wrapper, CLI and MCP are all 1.0.0 and both consumers declare the ^1 SDK peer range.",
            reopeningCondition: "The 1.0 surface is released and frozen. Reopen only for a deliberate 2.x break, which must restate every symbol and subpath decision.",
            reopeningDate: null,
            reopeningDateNote: "No calendar reopening date is scheduled.",
            packageVersionChanges: true,
            peerRangeChanges: true,
            completedCampaignRemainsHistorical: true,
        },
    };
}

function markdownTable(headers, rows) {
    return [
        `| ${headers.join(" | ")} |`,
        `| ${headers.map(() => "---").join(" | ")} |`,
        ...rows.map((row) => `| ${row.join(" | ")} |`),
    ].join("\n");
}

function md(value) {
    return `\`${String(value).replaceAll("`", "\\`")}\``;
}

function renderMarkdown(inventory) {
    const lines = [BANNER, "", "# 1.0 surface inventory", "", inventory.purpose, ""];
    lines.push("## Decision posture", "", `- Decision: ${md(inventory.decisionPosture.decision)}`, `- Symbol classification: ${md(inventory.decisionPosture.symbolClassification)}`, `- Reason: ${inventory.decisionPosture.reason}`, `- Reopening condition: ${inventory.decisionPosture.reopeningCondition}`, `- ${inventory.decisionPosture.reopeningDateNote}`, "- Package versions and SDK peer ranges changed: no.", "");
    lines.push("## Mechanical counts", "", markdownTable(["Evidence", "Count"], [
        ["SDK root symbols", String(inventory.sdk.rootSymbolCount)],
        ["Unique SDK symbols across root and subpaths", String(inventory.sdk.uniqueSymbolCount)],
        ["SDK subpaths", String(inventory.sdk.subpathCount)],
        ["Stability/deprecation annotations", String(inventory.sdk.stability.annotations.length)],
        ["Known pre-1.0 breaking changes", String(inventory.knownPre1xBreakingChanges.length)],
        ["Consumer packages", String(inventory.consumers.length)],
        ["Registry observations", String(inventory.registry.packages.length)],
    ]), "", "## SDK symbol decisions", "", "Every SDK symbol carries a maintainer decision from `docs/one-point-zero-classification.json`. A symbol with no entry there stays `undecided` rather than defaulting to stable.", "", markdownTable(["Symbol", "Decision", "Root", "Subpaths"], inventory.sdk.symbolDecisions.map((entry) => [entry.name, md(entry.decision), entry.root ? "yes" : "no", entry.subpaths.map(md).join("<br>") || "-"])), "", "## SDK subpaths", "", markdownTable(["Subpath", "Decision", "Symbols"], inventory.sdk.subpaths.map((entry) => [md(entry.path), md(entry.decision), entry.symbols.map(md).join("<br>")])), "");
    lines.push("## Stability and deprecations", "", inventory.sdk.stability.annotations.length > 0 ? markdownTable(["Tag", "Symbol", "File", "Line", "Annotation"], inventory.sdk.stability.annotations.map((entry) => [md(entry.tag), entry.symbol ?? "-", md(entry.file), String(entry.line), md(entry.annotation)])) : "No stability or deprecation annotations were found in the hand-written wrapper root.", "");
    lines.push("## CLI/MCP package and workflow evidence", "", markdownTable(["Package", "Version", "Node", "SDK peer"], inventory.consumers.map((entry) => [md(entry.name), md(entry.version), md(entry.nodeEngine ?? "-"), md(entry.sdkPeerRange ?? "-")])), "", "Workflow/parser evidence is recorded as source lines, not inferred behavior:", "", ...inventory.releaseWorkflowPeerParsing.flatMap((entry) => {
        if (entry.workflow) return [`### ${entry.workflow}`, "", `- workflow_dispatch: ${entry.workflowDispatch ? "present" : "absent"}`, `- tag trigger marker: ${entry.tagTrigger ? "present" : "absent"}`, "", "```text", ...entry.parserRelevantLines.map((line) => `${line.line}: ${line.text}`), "```", ""];
        return [`### ${entry.source}`, "", "```text", ...entry.peerRelatedLines.map((line) => `${line.line}: ${line.text}`), "```", ""];
    }));
    lines.push("## Known pre-1.0 breaking changes", "", markdownTable(["Removed", "Replacement"], inventory.knownPre1xBreakingChanges.map((entry) => [md(entry.removed), md(entry.replacement)])), "", "## Migration guide state", "", `- Source: ${md(inventory.migrationGuide.path)}`, `- 1.0 closure section present: ${inventory.migrationGuide.hasOnePointZeroClosure ? "yes" : "no"}`, "", markdownTable(["Level", "Heading", "Line"], inventory.migrationGuide.headings.map((heading) => [String(heading.level), heading.title, String(heading.line)])), "", "## Registry observation", "", `- Status: ${md(inventory.registry.status)}`, `- Queried at: ${md(inventory.registry.queriedAt)}`, `- Captured against source SHA: ${md(inventory.registry.capturedAgainstSha)}`, "", markdownTable(["Package", "Version", "Integrity"], inventory.registry.packages.map((entry) => [md(entry.name), md(entry.version), md(entry["dist.integrity"])])), "");
    return `${lines.join("\n").replace(/\n+$/, "")}\n`;
}

const inventory = buildInventory();
const expectedJson = `${JSON.stringify(inventory, null, 2)}\n`;
const expectedMd = renderMarkdown(inventory);

if (args.has("--write")) {
    fs.writeFileSync(absolute(JSON_OUTPUT), expectedJson);
    fs.writeFileSync(absolute(MD_OUTPUT), expectedMd);
    console.log(`wrote ${JSON_OUTPUT} and ${MD_OUTPUT} (${inventory.sdk.uniqueSymbolCount} symbols, ${inventory.sdk.subpathCount} subpaths)`);
} else if (args.has("--check")) {
    const stale = [];
    if (!fs.existsSync(absolute(JSON_OUTPUT)) || read(JSON_OUTPUT) !== expectedJson) stale.push(JSON_OUTPUT);
    if (!fs.existsSync(absolute(MD_OUTPUT)) || read(MD_OUTPUT) !== expectedMd) stale.push(MD_OUTPUT);
    if (stale.length > 0) {
        console.error(`1.0 surface inventory is stale: ${stale.join(", ")}. Run the generator with --write.`);
        process.exit(1);
    }
    console.log(`1.0 surface inventory is current (${inventory.sdk.uniqueSymbolCount} symbols, ${inventory.sdk.subpathCount} subpaths)`);
} else {
    console.error("usage: generate-one-point-zero-inventory.mjs [--write|--check]");
    process.exit(2);
}
